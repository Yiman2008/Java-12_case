def build(name, fn):
    tmp = os.path.join(OUT, "_pass1")
    os.makedirs(tmp, exist_ok=True)
    d = fn()
    d.fill_toc({t: "00" for _, t in d.headings})
    p1 = os.path.join(tmp, name + ".docx"); d.save(p1)
    pdf = to_pdf(p1, tmp)
    pages = heading_pages(pdf, d.headings, start_page=3)
    missing = [t for _, t in d.headings if t not in pages]
    if missing: print("WARNING missing pages:", missing)
    d = fn(pages)
    final = os.path.join(OUT, name + ".docx"); d.save(final)
    pdf = to_pdf(final, OUT)
    pages2 = heading_pages(pdf, d.headings, start_page=3)
    if pages2 != pages: print("WARNING page drift", {k: (pages.get(k), v) for k, v in pages2.items() if pages.get(k) != v})
    print(name, "ok", pdf)


