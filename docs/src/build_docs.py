def sample_result():
    from collections import OrderedDict
    groups = OrderedDict()
    for name, grp, subj, grade in C.SAMPLE_CSV[1:]:
        if grade >= 3:
            groups.setdefault(name, []).append(grade)
    rows = [(n, sum(g) / len(g), len(g)) for n, g in groups.items()]
    rows.sort(key=lambda r: -r[1])  # stable
    rows = rows[:3]
    hdr = ("name", "avg_grade", "n")
    cells = [hdr] + [(n, f"{a:.2f}", str(k)) for n, a, k in rows]
    w = [max(len(r[i]) for r in cells) for i in range(3)]
    sep = "+" + "+".join("-" * (x + 2) for x in w) + "+"
    def fmt(r, right=(False, True, True)):
        return "|" + "|".join(" " + (r[i].rjust(w[i]) if right[i] else r[i].ljust(w[i])) + " " for i in range(3)) + "|"
    lines = [sep, fmt(hdr, (False, False, False)), sep] + [fmt(r) for r in cells[1:]] + [sep, f"{len(rows)} строки, 4 мс"]
    return "\n".join(lines)


def csv_text():
    return "\n".join(",".join(str(x) for x in r) for r in C.SAMPLE_CSV)


